//! Server-side git hooks. One central `core.hooksPath` directory holds scripts that exec
//! the Reef binary (`reef hook <name>`), which talks to the database directly.

use reef_core::{Error, Result};
use std::path::{Path, PathBuf};
use tokio::process::Command;

pub const HOOK_NAMES: &[&str] = &["pre-receive"];
/// The object id git passes for a ref that does not exist yet (creation) or any more (deletion).
pub const ZERO_SHA: &str = "0000000000000000000000000000000000000000";

/// Write the hook scripts under `<data_dir>/hooks` and return that directory.
pub fn install(data_dir: &Path) -> Result<PathBuf> {
    let dir = data_dir.join("hooks");
    std::fs::create_dir_all(&dir)?;
    for name in HOOK_NAMES {
        let path = dir.join(name);
        let script = format!("#!/bin/sh\n# Generated by Reef. Do not edit.\nexec \"${{REEF_BIN:-reef}}\" hook {name} \"$@\"\n");
        let current = std::fs::read_to_string(&path).unwrap_or_default();
        if current != script {
            std::fs::write(&path, script)?;
        }
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o755))?;
        }
    }
    Ok(dir)
}

/// Is `new` reachable from `old`, i.e. is the update a fast-forward?
pub async fn is_ancestor(git: &Path, repo: &Path, old: &str, new: &str) -> Result<bool> {
    let out = Command::new(git).arg("-C").arg(repo).args(["merge-base", "--is-ancestor", old, new]).output().await?;
    Ok(out.status.success())
}

/// The ref `HEAD` of a bare repository points at (`refs/heads/main`), when it is symbolic.
pub async fn default_branch_ref(git: &Path, repo: &Path) -> Result<Option<String>> {
    let out = Command::new(git).arg("-C").arg(repo).args(["symbolic-ref", "-q", "HEAD"]).output().await?;
    if !out.status.success() {
        return Ok(None);
    }
    let s = String::from_utf8_lossy(&out.stdout).trim().to_string();
    Ok((!s.is_empty()).then_some(s))
}

/// Does updating a branch from `old` to `new` bring merge commits onto it? The commits
/// judged are `old..new`. For a branch being created (`old` is `ZERO_SHA`) they are the
/// commits not already on the default branch, `merge-base(default, new)..new`; when the two
/// share nothing (the default branch itself being created, or an unrelated history) the whole
/// history of `new` is judged. So a merge commit on a topic branch cut from the default branch
/// is caught, while the default branch's own history is not judged a second time.
pub async fn introduces_merge_commits(git: &Path, repo: &Path, old: &str, new: &str) -> Result<bool> {
    let range = if old == ZERO_SHA {
        let mut base = None;
        if let Some(def) = default_branch_ref(git, repo).await? {
            let out = Command::new(git).arg("-C").arg(repo).args(["merge-base", &def, new]).output().await?;
            let mb = String::from_utf8_lossy(&out.stdout).trim().to_string();
            if out.status.success() && !mb.is_empty() {
                base = Some(mb);
            }
        }
        match base {
            Some(mb) => format!("{mb}..{new}"),
            None => new.to_string(),
        }
    } else {
        format!("{old}..{new}")
    };
    let out = Command::new(git).arg("-C").arg(repo).args(["rev-list", "--merges", "-n", "1", &range]).output().await?;
    if !out.status.success() {
        return Err(Error::msg(format!("git rev-list {range}: {}", String::from_utf8_lossy(&out.stderr).trim())));
    }
    Ok(!out.stdout.is_empty())
}
